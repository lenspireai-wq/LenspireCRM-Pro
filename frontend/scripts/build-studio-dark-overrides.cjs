// Rebuild with: node scripts/build-studio-dark-overrides.cjs
// Keep legacy layout intact; translate its color declarations into theme tokens.
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const rootDir = path.resolve(__dirname, '..');
const source = postcss.parse(fs.readFileSync(path.join(rootDir,'app/globals.css'),'utf8'));
const output = postcss.root();
function token(raw, prop) {
 let rgb, alpha=1;
 if(raw.startsWith('#')) {
  let h=raw.slice(1); if(h.length===3||h.length===4)h=[...h].map(x=>x+x).join('');
  rgb=[0,2,4].map(i=>parseInt(h.slice(i,i+2),16)); if(h.length===8)alpha=parseInt(h.slice(6),16)/255;
 } else {
  const n=raw.match(/[\d.]+/g).map(Number); rgb=n.slice(0,3); if(n.length>3)alpha=n[3];
 }
 const [r,g,b]=rgb.map(x=>x/255), max=Math.max(r,g,b), min=Math.min(r,g,b), delta=max-min, light=(max+min)/2;
 let hue=0;if(delta)hue=(max===r?(g-b)/delta+(g<b?6:0):max===g?(b-r)/delta+2:(r-g)/delta+4)*60;
 const sat=delta===0?0:delta/(1-Math.abs(2*light-1));
 const isText=/^(color|fill|stroke|text-decoration-color|caret-color)$/.test(prop);
 const isBorder=prop.includes('border')||prop.includes('outline');
 const isShadow=prop.includes('shadow');
 if(max<.08 && (isShadow||alpha<1))return raw;
 let name;
 const cool=hue>=185&&hue<=285;
 if(isShadow)name=cool&&sat>.3?'--brand':'--line';
 else if(isText) {
  if(sat<.22 || (cool&&sat<.52)) name=light>.76?'--text':light>.35?'--muted':'--text-strong';
  else if(cool)name='--brand';
  else if(hue<20||hue>325)name='--danger';
  else if(hue<65)name='--warning';
  else if(hue<185)name='--success';
  else name='--brand';
 } else if(cool||sat<.22) {
  if(isBorder)name=sat>.48&&light>.32?'--brand':'--line';
  else if(cool&&sat>.5&&light>.34&&light<.74)name='--brand';
  else name=light<.07?'--bg':light<.16?'--surface':light<.3?'--panel':light<.75?'--surface-strong':'--surface';
 } else {
  const semantic=hue<20||hue>325?'danger':hue<65?'warning':hue<185?'success':'brand';
  name='--'+semantic;
  if(!isBorder && light<.3)name+='-soft';
 }
 const val=`var(${name})`;
 return alpha<1?`color-mix(in srgb, ${val} ${Math.round(alpha*100)}%, transparent)`:val;
}
function processNode(node,parent) {
 if(node.type==='atrule') {
  if(!node.nodes||/keyframes/i.test(node.name)||/print/.test(node.params))return;
  const copy=node.clone({nodes:[]}); node.nodes.forEach(n=>processNode(n,copy));if(copy.nodes.some(d => /^background/.test(d.prop) && d.value.includes('var(--brand)') && !d.value.includes('color-mix'))) copy.append({prop:'color',value:'var(--on-brand)'});
 if(copy.nodes.length)parent.append(copy);return;
 }
 if(node.type!=='rule'||/:root|data-theme|\.login(?!Submit)|\.ownerLogin|\.clientAuth/.test(node.selector))return;
 const copy=node.clone({nodes:[]});
 copy.selectors=node.selectors.map(s=>`:root[data-theme="dark"] ${s}`);
 node.nodes.forEach(d=>{
  if(d.type!=='decl'||d.prop.startsWith('--')||!/color|background|border|shadow|outline|fill|stroke/.test(d.prop))return;
  const value=d.value.replace(/#[\da-f]{3,8}\b|rgba?\(\s*[\d.]+\s*,\s*[\d.]+\s*,\s*[\d.]+(?:\s*,\s*[\d.]+)?\s*\)/gi,m=>token(m,d.prop));
  if(value!==d.value)copy.append(d.clone({value}));
 });
 if(copy.nodes.some(d => /^background/.test(d.prop) && d.value.includes('var(--brand)') && !d.value.includes('color-mix'))) copy.append({prop:'color',value:'var(--on-brand)'});
 if(copy.nodes.length)parent.append(copy);
}
source.nodes.forEach(n=>processNode(n,output));
const header='/* Generated by scripts/build-studio-dark-overrides.cjs from globals.css.\n   Module colors use the charcoal/champagne tokens; layout and print styles stay in globals.css. */\n';
fs.writeFileSync(path.join(rootDir,'app/studio-dark-modules.css'),header+output.toString()+'\n');
console.log(`Generated ${output.nodes.length} module color rules.`);
