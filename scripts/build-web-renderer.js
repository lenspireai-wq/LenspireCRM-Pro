const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const readBase64 = relative => fs.readFileSync(path.join(root, relative)).toString('base64');
const version = String(Date.now());
const html = read('src/renderer/index.html')
  .replace('<title>LenspireCRM · Studio Workspace</title>', '<title>LenspireCRM · Studio Workspace</title>\n  <meta name="theme-color" content="#0b1220">\n  <meta name="application-name" content="LenspireCRM">\n  <meta name="apple-mobile-web-app-capable" content="yes">\n  <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">\n  <link rel="manifest" href="/manifest.webmanifest">\n  <link rel="icon" href="/icons/icon-192.png">\n  <link rel="apple-touch-icon" href="/icons/icon-192.png">')
  .replace('href="style.css"', `href="/desktop-style.css?v=${version}"`)
  .replace('<script src="../../node_modules/chart.js/dist/chart.umd.js"></script>', `<script src="/desktop-chart.js?v=${version}"></script>\n  <script src="/desktop-xlsx.js?v=${version}"></script>\n  <script src="/web-bridge.js?v=${version}"></script>`)
  .replace('<script src="app.js"></script>', `<script src="/desktop-app.js?v=${version}"></script>`);
const source = [
  '// Generated by scripts/build-web-renderer.js. Do not edit by hand.',
  `export const WEB_RENDERER_VERSION = ${JSON.stringify(version)};`,
  `export const DESKTOP_HTML = ${JSON.stringify(html)};`,
  `export const DESKTOP_CSS = ${JSON.stringify(read('src/renderer/style.css'))};`,
  `export const DESKTOP_APP_JS = ${JSON.stringify(read('src/renderer/app.js').replace("sidebarHidden:false", "sidebarHidden:matchMedia('(max-width:900px)').matches"))};`,
  `export const WEB_BRIDGE_JS = ${JSON.stringify(read('cloudflare-worker/web-bridge.js'))};`,
  `export const CHART_JS = ${JSON.stringify(read('node_modules/chart.js/dist/chart.umd.js'))};`,
  `export const XLSX_JS = ${JSON.stringify(read('node_modules/xlsx/dist/xlsx.full.min.js'))};`,
  `export const LOGIN_HERO_PNG = ${JSON.stringify(readBase64('src/renderer/login-studio-camera-v2.png'))};`,
  `export const APP_ICON_PNG = ${JSON.stringify(readBase64('build/icon.png'))};`,
  ''
].join('\n');
fs.writeFileSync(path.join(root, 'cloudflare-worker/desktop-bundle.generated.js'), source);
console.log(`Built exact Windows renderer for web (${version}).`);
